export type NativeMediaAudioProbeFixtureCodec = 'ac3' | 'eac3';
export type NativeMediaAudioProbeFixtureChannelCount = 2 | 6;

function decodeBase64(base64: string): Uint8Array {
    const decoded = globalThis.atob(base64);
    const bytes = new Uint8Array(decoded.length);
    for (let byteIndex = 0; byteIndex < decoded.length; byteIndex += 1) {
        bytes[byteIndex] = decoded.charCodeAt(byteIndex);
    }
    return bytes;
}

/** Returns a fresh exact fMP4 sample for native MSE decoder qualification. */
export function createNativeMediaAudioProbeFixture(
    codec: NativeMediaAudioProbeFixtureCodec,
    channelCount: NativeMediaAudioProbeFixtureChannelCount
): Uint8Array {
    switch (`${codec}:${channelCount}`) {
        case 'ac3:2':
            return decodeBase64(AC3_PROBE_BASE64);
        case 'ac3:6':
            return decodeBase64(AC3_SURROUND_PROBE_BASE64);
        case 'eac3:2':
            return decodeBase64(EAC3_PROBE_BASE64);
        case 'eac3:6':
            return decodeBase64(EAC3_SURROUND_PROBE_BASE64);
        default:
            throw new RangeError('Native media audio probe fixture layout is unsupported');
    }
}
